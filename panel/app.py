@app.route('/add_user', methods=['POST'])
def add_user():
    if not session.get('logged_in'): return redirect(url_for('login'))
    username = request.form.get('username')
    password = request.form.get('password')
    if not username or not password: return "Error: Missing fields", 400
    if not _valid_ext(username) or not _valid_pwd(password): return "Error: invalid username or password format", 400

    conn = get_db_connection()
    with conn.cursor() as cursor:
        cursor.execute('INSERT INTO sub_users (extension, secret_password) VALUES (%s, %s)', (username, password))
        conn.commit()
    conn.close()
    generate_configurations()
    return redirect(url_for('dashboard'))


_FAILS = {}

def _check_login(given):
    ip = request.remote_addr
    count, first = _FAILS.get(ip, (0, time.time()))
    if time.time() - first > 900:
        count, first = 0, time.time()
    if count >= 5:
        abort(429)
    expected = os.getenv('ADMIN_PASSWORD', '')
    ok = bool(expected) and hmac.compare_digest(given.encode(), expected.encode())
    if ok:
        _FAILS.pop(ip, None)
    else:
        _FAILS[ip] = (count + 1, first)
    return ok

@app.route('/login', methods=['GET', 'POST'])
def login():
    if request.method == 'POST':
        if _check_login(request.form.get('password', '')):
            session['logged_in'] = True
            return redirect(url_for('dashboard'))
    return render_template('login.html')


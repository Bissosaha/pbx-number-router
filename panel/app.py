@app.route('/')
def dashboard():
    if not session.get('logged_in'): return redirect(url_for('login'))
    conn = get_db_connection()
    with conn.cursor() as cursor:
        cursor.execute('SELECT * FROM sub_users')
        users = cursor.fetchall()
        for user in users:
            ext = user['extension']
            user['id'] = ext
            user['username'] = ext
            user['sip_password'] = user['secret_password']
            cursor.execute('SELECT phone_number FROM assigned_numbers WHERE extension = %s', (ext,))
            user['numbers'] = [row['phone_number'] for row in cursor.fetchall()]
            user['num_count'] = len(user['numbers'])
            
        cursor.execute('SELECT COUNT(*) as active_count FROM sub_users')
        active_users = cursor.fetchone()['active_count']
        cursor.execute('SELECT COUNT(*) as total_numbers FROM assigned_numbers')
        total_numbers = cursor.fetchone()['total_numbers']

    conn.close()
    return render_template('dashboard.html', users=users, active_users=active_users, total_numbers=total_numbers)

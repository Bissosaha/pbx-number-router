@app.route('/api/get_users', methods=['GET'])
def api_get_users():
    if not API_SECRET_KEY or not hmac.compare_digest(request.headers.get('X-API-KEY', '').encode(), API_SECRET_KEY.encode()):
        return jsonify({"error": "Unauthorized"}), 401
    
    conn = get_db_connection()
    with conn.cursor() as cursor:
        cursor.execute('SELECT extension FROM sub_users')
        users = [row['extension'] for row in cursor.fetchall()]
    conn.close()
    return jsonify({"users": users}), 200

@app.route('/api/bot_assign', methods=['POST'])
def api_bot_assign():
    if not API_SECRET_KEY or not hmac.compare_digest(request.headers.get('X-API-KEY', '').encode(), API_SECRET_KEY.encode()):
        return jsonify({"error": "Unauthorized"}), 401

    data = request.json
    ext = data.get('extension')
    number_list = data.get('numbers', [])

    if not ext or not number_list or not _valid_ext(ext):
        return jsonify({"error": "Missing data"}), 400

    conn = get_db_connection()
    added_count = 0
    with conn.cursor() as cursor:
        for num in set(number_list):
            clean_num = str(num).strip()
            if clean_num and _valid_number(clean_num):
                try: 
                    cursor.execute('INSERT INTO assigned_numbers (phone_number, extension) VALUES (%s, %s)', (clean_num, ext))
                    added_count += 1
                except: pass
        conn.commit()
    conn.close()

    if added_count > 0:
        generate_configurations()

    return jsonify({"status": "success", "added": added_count}), 200

# --- 2. THE ENGINE: Perfect Asterisk Sync (With Custom Logger) ---
def generate_configurations():
    conn = get_db_connection()
    with conn.cursor() as cursor:
        cursor.execute("SELECT extension, secret_password FROM sub_users")
        users = cursor.fetchall()
        with open('/etc/asterisk/pjsip_custom_kuddin.conf', 'w') as f:
            f.write("; --- AUTO GENERATED BY KUDDIN WEB PANEL ---\n\n")
            for user in users:
                ext = user['extension']
                pwd = user['secret_password']
                f.write(f"[{ext}]\ntype=endpoint\ncontext=from-internal\ndisallow=all\nallow=ulaw,alaw,gsm,g722\nauth={ext}-auth\naors={ext}\ntransport=0.0.0.0-udp\nrewrite_contact=yes\nforce_rport=yes\nrtp_symmetric=yes\n\n[{ext}-auth]\ntype=auth\nauth_type=userpass\npassword={pwd}\nusername={ext}\n\n[{ext}]\ntype=aor\nmax_contacts=1\nqualify_frequency=30\n\n")

        cursor.execute("SELECT phone_number, extension FROM assigned_numbers")
        assigned_numbers = cursor.fetchall()
        with open('/etc/asterisk/extensions_custom_kuddin.conf', 'w') as f:
            f.write("; --- AUTO GENERATED ROUTING BY KUDDIN WEB PANEL ---\n\n")
            f.write("[from-internal-custom]\n")
            f.write("exten => _X.,1,Dial(PJSIP/${EXTEN},60)\n")
            f.write("exten => _X.,n,Hangup()\n")
            f.write('exten => h,1,System(echo "${STRFTIME(${EPOCH},,%Y-%m-%d %H:%M:%S)},${CDR(src)},${CDR(dst)},${CDR(disposition)},${CDR(billsec)}" >> /var/log/asterisk/kuddin_cdr.csv)\n\n')

            f.write("[custom-inbound-routing]\n")
            for row in assigned_numbers:
                clean_num = row['phone_number'].strip()
                ext = row['extension']
                f.write(f"exten => {clean_num},1,Dial(PJSIP/{ext},60)\n")
                f.write(f"exten => {clean_num},n,Hangup()\n")

            f.write("; Catch-all for unassigned numbers\n")
            f.write("exten => _X.,1,Dial(PJSIP/1001,60)\n")
            f.write("exten => _X.,n,Hangup()\n")
            f.write('exten => h,1,System(echo "${STRFTIME(${EPOCH},,%Y-%m-%d %H:%M:%S)},${CDR(src)},${CDR(dst)},${CDR(disposition)},${CDR(billsec)}" >> /var/log/asterisk/kuddin_cdr.csv)\n\n')

    conn.close()
    os.system('asterisk -rx "core reload"')
    os.system('asterisk -rx "dialplan reload"')

# --- 3. THE AUTO-CLEANER (24-Hour Expiration) ---
def auto_cleanup_expired_numbers():
    while True:
        try:
            conn = get_db_connection()
            deleted_count = 0
            with conn.cursor() as cursor:
                cursor.execute("DELETE FROM assigned_numbers WHERE assigned_at < NOW() - INTERVAL 24 HOUR")
                deleted_count = cursor.rowcount
                conn.commit()
            conn.close()
            if deleted_count > 0:
                print(f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] Auto-Cleaner: Deleted {deleted_count} expired numbers.")
                generate_configurations()
        except Exception as e:
            print(f"Auto-Cleaner Error: {e}")
        time.sleep(600)

import re as _re

def _valid_number(n):
    return bool(_re.fullmatch(r'\+?[0-9]{6,20}', str(n).strip()))

def _valid_ext(e):
    return bool(_re.fullmatch(r'[0-9]{3,6}', str(e).strip()))

def _valid_pwd(p):
    return bool(_re.fullmatch(r'[A-Za-z0-9_@!#%+.\-]{8,64}', str(p)))


@app.route('/assign_numbers/<ext>', methods=['POST'])
def assign_numbers(ext):
    if not _valid_ext(ext): return "Bad extension", 400
    if not session.get('logged_in'): return redirect(url_for('login'))
    number_list = [n.strip() for n in request.form.get('numbers_list', '').split('\n') if n.strip() and _valid_number(n)]
    conn = get_db_connection()
    with conn.cursor() as cursor:
        # We removed the DELETE command here so it APPENDS new numbers!
        for num in set(number_list):
            try: 
                cursor.execute('INSERT INTO assigned_numbers (phone_number, extension) VALUES (%s, %s)', (num, ext))
            except: 
                pass # Silently ignore duplicates
        conn.commit()
    conn.close()
    generate_configurations()
    return redirect(url_for('dashboard'))

